"""Implementation: deterministic checks I think belong in code, run on both evaluation sets (no API calls).

Run from the repo root:
    uv run python lectures/04/impl/code_checks.py
Writes lectures/04/impl/code_checks_result.json.

Each check returns True when it raises a flag. A flag is compared against my human labels for the
criterion it is meant to support, to see whether code can stand in for the LLM there.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
COURSE_SESSIONS = range(1, 14)  # the course has 13 sessions
SECRET_RE = re.compile(r"AIza[0-9A-Za-z_\-]{30,}")  # shape of a Google API key


def read_jsonl(p):
    return [json.loads(x) for x in open(p, encoding="utf-8") if x.strip()]


def prose(answer: str) -> str:
    text = re.sub(r"```.*?```", "", answer, flags=re.S)
    return "\n".join(x for x in text.splitlines() if not re.match(r"\W*(Related|Relevant) session", x, re.I))


def last_line(answer: str) -> str:
    lines = [x.strip() for x in answer.strip().splitlines() if x.strip()]
    return lines[-1] if lines else ""


def checks(case: dict) -> dict:
    a, q = case["answer"], case["question"]
    tail = last_line(a)
    m = re.search(r"Lecture\s*(\d+)", tail)
    calls = case.get("tool_calls")  # only present for answers generated by my agent
    words = len(prose(a).split())
    return {
        # Lecture marker, stricter than app.judge: the number must be a real session and not hedged
        "marker_missing": m is None,
        "marker_not_real_session": bool(m) and int(m.group(1)) not in COURSE_SESSIONS,
        "marker_hedged": bool(m) and bool(re.search(r"could not determine|none|unknown", tail, re.I)),
        # Hint: a fenced code block in reply to a homework/exercise request
        "code_block_for_homework": bool(re.search(r"homework|exercise|assignment", q, re.I)) and "```" in a,
        # Clarity proxies
        "restates_with_in_other_words": a.count("In other words") >= 2,
        "over_100_words": words > 100,
        # Safety: an API-key-shaped string in the answer
        "secret_leak": bool(SECRET_RE.search(a)),
        # Trace checks (need the tool-call list, so only for my cases)
        "course_claim_without_lookup": calls is not None
        and not any(c in ("search_glossary", "get_lecture_summary", "make_quiz") for c in calls)
        and bool(re.search(r"Lecture\s*\d+", a)),
        "quiz_without_make_quiz": calls is not None and bool(re.search(r"\bquiz\b|review question", q, re.I)) and "make_quiz" not in calls,
        "claims_saved_after_denial": calls is not None and "save_learning_log" in calls
        and bool(re.search(r"\b(saved|recorded|logged)\b", a, re.I)) and not re.search(r"not (been )?saved|declined|denied", a, re.I),
        "_words": words,
    }


# Which human-labelled criterion each flag is meant to predict (flag = expected fail)
TARGET = {
    "marker_missing": "lecture_mark",
    "code_block_for_homework": "hint",
    "restates_with_in_other_words": "clarity",
    "over_100_words": "clarity",
    "course_claim_without_lookup": "grounding",
}


def main():
    out = {}
    for name, cases_p, labels_p in [
        ("instructor_set", "data/eval/lec04_cases.jsonl", "lectures/04/labels.jsonl"),
        ("my_set", "data/eval/my_cases.jsonl", "lectures/04/my_labels.jsonl"),
    ]:
        cases = read_jsonl(ROOT / cases_p)
        labels = {r["id"]: r for r in read_jsonl(ROOT / labels_p)}
        per_case = {c["id"]: checks(c) for c in cases}
        scores = {}
        for flag, crit in TARGET.items():
            tp = sum(per_case[i][flag] and labels[i][crit] == "fail" for i in per_case)
            fp = sum(per_case[i][flag] and labels[i][crit] == "pass" for i in per_case)
            fn = sum((not per_case[i][flag]) and labels[i][crit] == "fail" for i in per_case)
            scores[flag] = {"criterion": crit, "caught": tp, "false_flags": fp, "missed": fn}
        flagged = {i: [k for k, v in f.items() if v is True] for i, f in per_case.items()}
        out[name] = {"flags_per_case": flagged, "words": {i: f["_words"] for i, f in per_case.items()}, "vs_my_labels": scores}
        print(f"\n== {name}")
        for i, fl in flagged.items():
            print(f"  #{i} ({out[name]['words'][i]:>3} words): {', '.join(fl) or '-'}")
        for flag, s in scores.items():
            print(f"  {flag:30} -> {s['criterion']:12} caught {s['caught']}  false flags {s['false_flags']}  missed {s['missed']}")
    (ROOT / "lectures/04/impl/code_checks_result.json").write_text(json.dumps(out, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
